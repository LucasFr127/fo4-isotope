void CheckRgb(LinearRgb actual, LinearRgb expected, double tolerance)
{
    FO4HDR_CHECK(std::abs(actual.red - expected.red) <= tolerance);
    FO4HDR_CHECK(std::abs(actual.green - expected.green) <= tolerance);
    FO4HDR_CHECK(std::abs(actual.blue - expected.blue) <= tolerance);
}

void CheckContainedRgb(LinearRgb value, double peak)
{
    for (const auto channel : {value.red, value.green, value.blue})
    {
        FO4HDR_CHECK(std::isfinite(channel));
        FO4HDR_CHECK(channel >= 0.0 && channel <= peak);
    }
}

[[nodiscard]] double Bt2020Luminance(LinearRgb value)
{
    return 0.2627 * value.red + 0.6780 * value.green +
        0.0593 * value.blue;
}

